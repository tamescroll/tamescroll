// Builds the extension into dist/chrome and dist/firefox.
//
//   node build.mjs             bundle from the committed gen/engine.json
//   node build.mjs --compile   first regenerate gen/engine.json with the
//                              Rust compiler in compile/ (needs cargo)
//
// Everything a page runs is produced here, at build time, from files in
// this repo. Nothing executable is ever fetched at runtime.
import { build } from 'esbuild';
import { execFileSync } from 'node:child_process';
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SITES, allMatches } from './src/sites.js';

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, '..');
const pkg = JSON.parse(readFileSync(join(here, 'package.json'), 'utf8'));

if (process.argv.includes('--compile')) {
  execFileSync('cargo', ['run', '--release', '--quiet', '--', join(repo, 'rules'), join(here, 'gen', 'engine.json')], {
    cwd: join(here, 'compile'),
    stdio: 'inherit',
  });
}

const engine = JSON.parse(readFileSync(join(here, 'gen', 'engine.json'), 'utf8'));

/** The engine's scriptlet code for YouTube, picked by host at run time. */
export function youtubeAdsScript(eng) {
  const branches = ['www.youtube.com', 'm.youtube.com']
    .filter((h) => eng.hosts[h] && eng.hosts[h].script)
    .map((h) => `  if (location.hostname === ${JSON.stringify(h)}) {\n${eng.hosts[h].script}\n  }`);
  return (
    '// GENERATED by extension/build.mjs from gen/engine.json -- do not edit.\n' +
    '// The ad scriptlets the app\'s adblock engine injects on YouTube, compiled\n' +
    '// from the same lists by the same engine (extension/compile).\n' +
    '(function () {\n  if (window.__TS_EXT_ADS__) return;\n  window.__TS_EXT_ADS__ = 1;\n' +
    branches.join('\n') +
    '\n})();\n'
  );
}

/** kid-controls.js with only the autoplay control switched on. */
export function autoplayScript(source) {
  const token = '/*TS_KID*/ null';
  if (!source.includes(token)) throw new Error('kid-controls.js lost its /*TS_KID*/ token');
  return (
    '// GENERATED by extension/build.mjs from app/src-tauri/kid-controls.js.\n' +
    source.replace(token, '{"swipeOff":false,"lock":false,"autoplayOff":true}')
  );
}

export function manifest(target) {
  const matches = allMatches();
  const m = {
    manifest_version: 3,
    name: 'Tame Scroll',
    short_name: 'Tame Scroll',
    version: pkg.version,
    // Safari rejects more than 112 characters; Chrome allows 132.
    description: 'A calmer social media: no algorithmic feeds, no Shorts or Reels, no autoplay, optional blur.',
    icons: { 16: 'icons/icon-16.png', 32: 'icons/icon-32.png', 48: 'icons/icon-48.png', 128: 'icons/icon-128.png' },
    action: { default_popup: 'popup.html', default_icon: { 16: 'icons/icon-16.png', 32: 'icons/icon-32.png' } },
    permissions: ['storage', 'scripting', 'alarms'],
    host_permissions: matches,
    content_scripts: [{ matches, js: ['content.js'], run_at: 'document_start', all_frames: false }],
  };
  if (target === 'firefox') {
    m.background = { scripts: ['background.js'] };
    m.browser_specific_settings = {
      gecko: {
        id: 'extension@tamescroll.app',
        strict_min_version: '128.0',
        data_collection_permissions: { required: ['none'] },
      },
    };
  } else if (target === 'safari') {
    // Packaged into a Mac and iPhone app by Apple's converter on a cloud
    // Mac (.github/workflows/safari.yml); this folder is its input.
    m.background = { service_worker: 'background.js' };
  } else {
    m.background = { service_worker: 'background.js' };
    m.minimum_chrome_version = '111';
  }
  return m;
}

async function bundle(outdir) {
  await build({
    entryPoints: {
      background: join(here, 'src/background.js'),
      content: join(here, 'src/content.js'),
      popup: join(here, 'src/popup-main.js'),
      'youtube-shorts': join(here, 'src/main-shorts.js'),
      'reddit-discovery': join(here, 'src/reddit-discovery.js'),
    },
    outdir,
    bundle: true,
    format: 'iife',
    target: ['chrome111', 'firefox128'],
    loader: { '.txt': 'text', '.css': 'text' },
    // Readable output: store reviewers read it, and Firefox asks for it.
    minify: false,
    legalComments: 'inline',
    logLevel: 'warning',
  });
}

async function main() {
  const kid = readFileSync(join(repo, 'app/src-tauri/kid-controls.js'), 'utf8');
  for (const target of ['chrome', 'firefox', 'safari']) {
    const out = join(here, 'dist', target);
    rmSync(out, { recursive: true, force: true });
    mkdirSync(out, { recursive: true });
    await bundle(out);
    writeFileSync(join(out, 'youtube-ads.js'), youtubeAdsScript(engine));
    writeFileSync(join(out, 'youtube-autoplay.js'), autoplayScript(kid));
    cpSync(join(here, 'src/popup.html'), join(out, 'popup.html'));
    cpSync(join(here, 'src/popup.css'), join(out, 'popup.css'));
    cpSync(join(here, 'icons'), join(out, 'icons'), { recursive: true });
    // Inter, bundled (OFL-1.1): Windows does not have it, and the fallback
    // was what made the popup's type feel off.
    mkdirSync(join(out, 'fonts'), { recursive: true });
    const fonts = join(here, 'node_modules/@fontsource-variable/inter');
    cpSync(join(fonts, 'files/inter-latin-wght-normal.woff2'), join(out, 'fonts/inter.woff2'));
    cpSync(join(fonts, 'LICENSE'), join(out, 'fonts/LICENSE-inter.txt'));
    writeFileSync(join(out, 'manifest.json'), JSON.stringify(manifest(target), null, 2) + '\n');
    console.log(`built dist/${target}`);
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  await main();
}
